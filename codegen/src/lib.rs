//! Compile declarative XML into ordinary iced-libadwaita Rust view code.
//! No XML parser is required in the resulting application.
use std::{fs, path::Path};

#[derive(Debug)]
pub enum Error {
    Xml(roxmltree::Error),
    Io(std::io::Error),
    Invalid(String),
}
impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self { Self::Xml(e) => write!(f, "{e}"), Self::Io(e) => write!(f, "{e}"), Self::Invalid(e) => write!(f, "{e}") }
    }
}
impl std::error::Error for Error {}
impl From<roxmltree::Error> for Error { fn from(e: roxmltree::Error) -> Self { Self::Xml(e) } }
impl From<std::io::Error> for Error { fn from(e: std::io::Error) -> Self { Self::Io(e) } }

/// Compiles an XML UI file into a Rust module at build time.
pub fn compile_file(input: impl AsRef<Path>, output: impl AsRef<Path>) -> Result<(), Error> {
    let input = input.as_ref();
    let generated = compile(&fs::read_to_string(input)?)?;
    if let Some(parent) = output.as_ref().parent() { fs::create_dir_all(parent)?; }
    fs::write(output, generated)?;
    println!("cargo:rerun-if-changed={}", input.display());
    Ok(())
}

/// Supported components are deliberately explicit: unsupported catalog entries fail at build time.
/// Expressions and callback names are Rust paths, type-checked by rustc in the consuming app.
pub fn compile(xml: &str) -> Result<String, Error> {
    let doc = roxmltree::Document::parse(xml)?;
    let root = doc.root_element();
    if root.tag_name().name() != "interface" { return Err(Error::Invalid("root must be <interface>".into())); }
    let nodes: Vec<_> = root.children().filter(|n| n.is_element()).collect();
    if nodes.len() != 1 { return Err(Error::Invalid("<interface> must contain one root <element>".into())); }
    let body = element(nodes[0])?;
    Ok(format!("// Generated by iced-libadwaita-codegen. Do not edit.\npub fn view<'a>() -> iced::Element<'a, crate::Message, iced_libadwaita::Theme> {{\n    {body}\n}}\n"))
}

fn rust_string(s: &str) -> String { format!("{s:?}") }
fn element(node: roxmltree::Node<'_, '_>) -> Result<String, Error> {
    if node.tag_name().name() != "element" { return Err(Error::Invalid("expected <element>".into())); }
    let kind = node.attribute("type").ok_or_else(|| Error::Invalid("element requires type".into()))?;
    let mut properties = std::collections::BTreeMap::new();
    let mut children = Vec::new();
    for child in node.children().filter(|n| n.is_element()) {
        match child.tag_name().name() {
            "property" => {
                let name = child.attribute("name").ok_or_else(|| Error::Invalid("property requires name".into()))?;
                if properties.insert(name.to_owned(), child.text().unwrap_or("").trim().to_owned()).is_some() {
                    return Err(Error::Invalid(format!("duplicate property {name}")));
                }
            }
            "element" => children.push(element(child)?),
            other => return Err(Error::Invalid(format!("unknown XML node {other}"))),
        }
    }
    let take = |key: &str| properties.get(key).map(String::as_str);
    let expr = match kind {
        "Text" => {
            if !children.is_empty() { return Err(Error::Invalid("Text cannot have children".into())); }
            format!("iced::widget::text({})", rust_string(take("value").ok_or_else(|| Error::Invalid("Text needs value".into()))?))
        }
        "Column" | "Row" => {
            let ctor = if kind == "Column" { "column" } else { "row" };
            let mut s = format!("iced::widget::{ctor}()");
            for child in children { s.push_str(&format!(".push({child})")); }
            if let Some(spacing) = take("spacing") {
                let n: u16 = spacing.parse().map_err(|_| Error::Invalid("spacing must be an unsigned integer".into()))?;
                s.push_str(&format!(".spacing({n})"));
            }
            s
        }
        "Button" => {
            if !children.is_empty() { return Err(Error::Invalid("Button child elements not supported; use label".into())); }
            let label = take("label").ok_or_else(|| Error::Invalid("Button needs label".into()))?;
            let mut s = format!("iced::widget::button(iced::widget::text({}))", rust_string(label));
            if let Some(msg) = take("on_press") {
                if !msg.split("::").all(|part| !part.is_empty() && part.chars().enumerate().all(|(i,c)| if i == 0 { c.is_ascii_alphabetic() || c == '_' } else { c.is_ascii_alphanumeric() || c == '_' })) {
                    return Err(Error::Invalid("on_press must be a Rust enum variant path".into()));
                }
                s.push_str(&format!(".on_press({msg})"));
            }
            s
        }
        "PreferencesPage" => {
            let mut s = "iced_libadwaita::widget::PreferencesPage::new()".to_owned();
            for child in children { s.push_str(&format!(".push({child})")); }
            s
        }
        "PreferencesGroup" => {
            let mut s = "iced_libadwaita::widget::PreferencesGroup::new()".to_owned();
            if let Some(title) = take("title") { s.push_str(&format!(".title({})", rust_string(title))); }
            for child in children { s.push_str(&format!(".push({child})")); }
            s
        }
        "ActionRow" => {
            let mut s = format!("iced_libadwaita::widget::ActionRow::new({})", rust_string(take("title").ok_or_else(|| Error::Invalid("ActionRow needs title".into()))?));
            if let Some(subtitle) = take("subtitle") { s.push_str(&format!(".subtitle({})", rust_string(subtitle))); }
            if !children.is_empty() { return Err(Error::Invalid("ActionRow child slots not yet supported".into())); }
            s
        }
        _ => return Err(Error::Invalid(format!("unsupported component type {kind}; add a typed mapping before using it"))),
    };
    let allowed: &[&str] = match kind {
        "Text" => &["value"], "Column" | "Row" => &["spacing"],
        "Button" => &["label", "on_press"], "PreferencesPage" => &[],
        "PreferencesGroup" => &["title"], "ActionRow" => &["title", "subtitle"], _ => &[],
    };
    for key in properties.keys() { if !allowed.contains(&key.as_str()) { return Err(Error::Invalid(format!("{kind} has no supported property {key}"))); } }
    Ok(format!("({expr}).into()"))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn generates_rust() {
        let src = compile(r#"<interface><element type="Column"><element type="Button"><property name="label">Play</property><property name="on_press">Message::Play</property></element></element></interface>"#).unwrap();
        assert!(src.contains("Message::Play"));
        assert!(src.contains("iced::widget::column"));
    }
    #[test]
    fn rejects_unknown_components() {
        assert!(compile(r#"<interface><element type="Unmapped"/></interface>"#).is_err());
    }
}
