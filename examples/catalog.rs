//! Prints the component catalog as Markdown: `cargo run --example catalog > docs/lib/components-catalog.md`.
//! The catalog (`iced_libadwaita::catalog`) is the single source of truth for tags, so docs and
//! any declarative layer (XML / JSX-like) stay in sync with the code.

use iced_libadwaita::catalog::COMPONENTS;

fn list(items: &[&str]) -> String {
    if items.is_empty() {
        "–".into()
    } else {
        items
            .iter()
            .map(|i| format!("`{i}`"))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

fn main() {
    println!("# Component catalog\n");
    println!(
        "Generated by `cargo run --example catalog` from `iced_libadwaita::catalog::COMPONENTS` ({} components).\n",
        COMPONENTS.len()
    );
    println!("| Tag | Mirrors | Constructor | Properties | Slots | Events |");
    println!("|---|---|---|---|---|---|");
    for c in COMPONENTS {
        println!(
            "| `{}` | {} | `{}` | {} | {} | {} |",
            c.tag,
            c.adw,
            c.ctor,
            list(c.props),
            list(c.slots),
            list(c.events)
        );
    }
}
